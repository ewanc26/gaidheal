//! C code generation for Gàidheal.
//!
//! Lowers the parser's block AST to readable portable C99 against
//! `runtime/gaidheal_runtime.h`. Control flow maps directly: `ma`/`mha`
//! become `if`, `no` becomes `else`, `cuairt` becomes a `while` whose
//! condition pops before the body, `chuairt` becomes a `do`/`while` whose
//! condition pops after the body, and `cùl`/`chuìl` become C `break`/
//! `continue` — which reproduce the interpreter's control-flow semantics
//! exactly, including the trailing condition pop a `chuairt` loop takes
//! after a continue.

use crate::parser::{Block, IfForm, LoopKind, LoopStmt, IfStmt, Op};
use std::fmt::Write as _;

/// Absolute path of the runtime header, baked at build time the way the
/// generated C of the other esolang front-ends references its runtime.
pub fn runtime_header_path() -> &'static str {
    concat!(env!("CARGO_MANIFEST_DIR"), "/runtime/gaidheal_runtime.h")
}

/// Emit a complete, compilable C translation unit for the program.
pub fn emit_c(program: &Block, source_name: &str, depth: usize, header_path: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "/* Generated by gaidheal from {} */", source_name);
    let _ = writeln!(out, "#define GH_STACK_MAX {}", depth);
    let _ = writeln!(out, "#include \"{}\"", header_path.replace('\\', "/"));
    let _ = writeln!(out);
    let _ = writeln!(out, "int main(void) {{");
    emit_block(&mut out, program, 1);
    let _ = writeln!(out, "    return 0;");
    let _ = writeln!(out, "}}");
    out
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

fn emit_block(out: &mut String, block: &Block, level: usize) {
    for op in block {
        emit_op(out, op, level);
    }
}

fn emit_op(out: &mut String, op: &Op, level: usize) {
    let pad = indent(level);
    match op {
        Op::Push(n) => {
            let _ = writeln!(out, "{}gh_push({});", pad, c_double_literal(*n));
        }
        Op::Copy(i) => {
            let _ = writeln!(out, "{}gh_copy({});", pad, i);
        }
        Op::Roll(i) => {
            let _ = writeln!(out, "{}gh_roll({});", pad, i);
        }
        Op::Dup => {
            let _ = writeln!(out, "{}gh_dup();", pad);
        }
        Op::Over => {
            let _ = writeln!(out, "{}gh_over();", pad);
        }
        Op::StackDepth => {
            let _ = writeln!(out, "{}gh_push_depth();", pad);
        }
        Op::Swap => {
            let _ = writeln!(out, "{}gh_swap();", pad);
        }
        Op::Reverse => {
            let _ = writeln!(out, "{}gh_reverse();", pad);
        }
        Op::Tuck => {
            let _ = writeln!(out, "{}gh_tuck();", pad);
        }
        Op::Drop => {
            let _ = writeln!(out, "{}gh_drop();", pad);
        }
        Op::Nip => {
            let _ = writeln!(out, "{}gh_nip();", pad);
        }
        Op::Clear => {
            let _ = writeln!(out, "{}gh_clear();", pad);
        }
        Op::Add => {
            let _ = writeln!(out, "{}gh_add();", pad);
        }
        Op::Sub => {
            let _ = writeln!(out, "{}gh_sub();", pad);
        }
        Op::Mul => {
            let _ = writeln!(out, "{}gh_mul();", pad);
        }
        Op::Div => {
            let _ = writeln!(out, "{}gh_div();", pad);
        }
        Op::Rem => {
            let _ = writeln!(out, "{}gh_rem();", pad);
        }
        Op::Pow => {
            let _ = writeln!(out, "{}gh_pow();", pad);
        }
        Op::Lt => {
            let _ = writeln!(out, "{}gh_lt();", pad);
        }
        Op::Gt => {
            let _ = writeln!(out, "{}gh_gt();", pad);
        }
        Op::Eq => {
            let _ = writeln!(out, "{}gh_eq();", pad);
        }
        Op::PrintNum => {
            let _ = writeln!(out, "{}gh_print_num();", pad);
        }
        Op::PrintChar => {
            let _ = writeln!(out, "{}gh_print_char();", pad);
        }
        Op::ReadNum => {
            let _ = writeln!(out, "{}gh_read_num();", pad);
        }
        Op::ReadChar => {
            let _ = writeln!(out, "{}gh_read_char();", pad);
        }
        Op::EofFlag => {
            let _ = writeln!(out, "{}gh_eof_flag();", pad);
        }
        Op::Break => {
            let _ = writeln!(out, "{}break;", pad);
        }
        Op::Continue => {
            let _ = writeln!(out, "{}continue;", pad);
        }
        Op::If(stmt) => emit_if(out, stmt, level),
        Op::Loop(stmt) => emit_loop(out, stmt, level),
    }
}

/// `ma` runs its block when the popped condition is nonzero; `mha` when it
/// is zero. The optional `no` branch becomes the C `else`.
fn emit_if(out: &mut String, stmt: &IfStmt, level: usize) {
    let pad = indent(level);
    let cond = match stmt.form {
        IfForm::Ma => "gh_pop() != 0.0",
        IfForm::Mha => "gh_pop() == 0.0",
    };
    let _ = writeln!(out, "{}if ({}) {{", pad, cond);
    emit_block(out, &stmt.then_branch, level + 1);
    if let Some(else_branch) = &stmt.else_branch {
        let _ = writeln!(out, "{}}} else {{", pad);
        emit_block(out, else_branch, level + 1);
    }
    let _ = writeln!(out, "{}}}", pad);
}

fn emit_loop(out: &mut String, stmt: &LoopStmt, level: usize) {
    let pad = indent(level);
    match stmt.kind {
        LoopKind::While => {
            // cuairt pops its condition BEFORE each iteration.
            let _ = writeln!(out, "{}while (gh_pop() != 0.0) {{", pad);
            emit_block(out, &stmt.body, level + 1);
            let _ = writeln!(out, "{}}}", pad);
        }
        LoopKind::DoWhile => {
            // chuairt pops its condition AFTER the body; a `continue`
            // jumps to that same condition pop.
            let _ = writeln!(out, "{}do {{", pad);
            emit_block(out, &stmt.body, level + 1);
            let _ = writeln!(out, "{}}} while (gh_pop() != 0.0);", pad);
        }
        LoopKind::Infinite => {
            let _ = writeln!(out, "{}for (;;) {{", pad);
            emit_block(out, &stmt.body, level + 1);
            let _ = writeln!(out, "{}}}", pad);
        }
    }
}

/// Format a double as a C99 numeric literal with the value's exact bits.
/// `NaN` and infinities map to the C macros; integral values below 1e15
/// stay short (parsed as int literals, then converted — exact); anything
/// else uses Rust's shortest round-trip decimal, optionally forced to a
/// double literal, which every correctly-rounded `strtod` reads back
/// bit-exactly.
pub fn c_double_literal(v: f64) -> String {
    if v.is_nan() {
        return "NAN".to_string();
    }
    if v.is_infinite() {
        return if v < 0.0 { "(-INFINITY)".to_string() } else { "INFINITY".to_string() };
    }
    if v == 0.0 && v.is_sign_negative() {
        return "-0.0".to_string();
    }
    let short = format!("{}", v);
    if v == v.trunc() && v.abs() >= 1e15 {
        // Too large for an integer literal: append ".0" so C parses it as
        // an exact double constant.
        return format!("{}.0", short);
    }
    short
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::interpreter::Interpreter;
    use crate::parser::parse_program;
    use std::io::Cursor;
    use std::process::Command;

    fn interpreter_output(src: &str, input: &str) -> (String, String, i32) {
        let program = parse_program(src).unwrap();
        let mut interp = Interpreter::new(Cursor::new(input.as_bytes().to_vec()), Vec::new());
        interp.run(&program).unwrap();
        (String::from_utf8(interp.into_output()).unwrap(), String::new(), 0)
    }

    /// Compile a program to C, build it with the system C compiler, run it
    /// with the given input, and return (stdout, stderr, exit code).
    /// Skips (with a note) when no C compiler is available.
    fn compiled_output(src: &str, input: &str) -> Option<(String, String, i32)> {
        let cc = std::env::var("GAIDHEAL_CC").unwrap_or_else(|_| "cc".to_string());
        let program = parse_program(src).unwrap();
        let c = emit_c(&program, "test.gaidheal", 1000, runtime_header_path());
        // A unique directory per call: cargo runs tests in parallel.
        static COUNTER: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
        let n = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!("gaidheal-{}-{}", std::process::id(), n));
        std::fs::create_dir_all(&dir).unwrap();
        let c_path = dir.join("test.c");
        let bin_path = dir.join("test");
        std::fs::write(&c_path, &c).unwrap();
        let build = Command::new(&cc)
            .arg("-std=c99")
            .arg("-O2")
            .arg(c_path.as_os_str())
            .arg("-lm")
            .arg("-o")
            .arg(bin_path.as_os_str())
            .output()
            .expect("failed to spawn the C compiler");
        if !build.status.success() {
            panic!("C compiler failed:\n{}", String::from_utf8_lossy(&build.stderr));
        }
        let run = Command::new(bin_path.as_os_str())
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
            .and_then(|mut child| {
                use std::io::Write;
                if let Some(mut stdin) = child.stdin.take() {
                    stdin.write_all(input.as_bytes()).ok();
                }
                child.wait_with_output()
            })
            .expect("failed to run the compiled program");
        let _ = std::fs::remove_dir_all(&dir);
        Some((
            String::from_utf8_lossy(&run.stdout).to_string(),
            String::from_utf8_lossy(&run.stderr).to_string(),
            run.status.code().unwrap_or(-1),
        ))
    }

    fn assert_parity(src: &str, input: &str) {
        let (i_out, _, i_rc) = interpreter_output(src, input);
        let Some((c_out, c_err, c_rc)) = compiled_output(src, input) else {
            return;
        };
        assert_eq!(i_out, c_out, "stdout mismatch for {:?}", src);
        assert_eq!(i_rc, c_rc, "exit code mismatch for {:?}", src);
        assert!(c_err.is_empty(), "unexpected stderr for {:?}: {}", src, c_err);
    }

    #[test]
    fn literal_formatting() {
        assert_eq!(c_double_literal(5.0), "5");
        assert_eq!(c_double_literal(-3.0), "-3");
        assert_eq!(c_double_literal(2.5), "2.5");
        assert_eq!(c_double_literal(1000.0), "1000");
        assert_eq!(c_double_literal(0.1), "0.1");
    }

    #[test]
    fn emits_readable_c() {
        let program = parse_program("cuir 5 gcuairt chuir 0 mha cuìl criòch tog abair cuir 1 shuim criòch").unwrap();
        let c = emit_c(&program, "cunntas.gaidheal", 1000, "/tmp/gaidheal_runtime.h");
        assert!(c.contains("#define GH_STACK_MAX 1000"));
        assert!(c.contains("#include \"/tmp/gaidheal_runtime.h\""));
        assert!(c.contains("gh_push(5);"));
        assert!(c.contains("for (;;) {"));
        assert!(c.contains("if (gh_pop() == 0.0) {"));
        assert!(c.contains("break;"));
        assert!(c.contains("gh_dup();"));
        assert!(c.contains("gh_print_num();"));
        assert!(c.contains("gh_sub();"));
        assert!(c.contains("    }"));
    }

    #[test]
    fn if_else_and_loops() {
        let program = parse_program("cuir 1 ma abair no abair criòch cuairt chuìl criòch chuairt tog cuìl criòch").unwrap();
        let c = emit_c(&program, "t.gaidheal", 1000, "/tmp/gaidheal_runtime.h");
        assert!(c.contains("} else {"));
        assert!(c.contains("while (gh_pop() != 0.0) {"));
        assert!(c.contains("continue;"));
        assert!(c.contains("} while (gh_pop() != 0.0);"));
    }

    #[test]
    fn compiled_parity_arithmetic() {
        for src in [
            "cuir 2 cuir 3 suim abair",
            "cuir 7 cuir 2 dhealaich abair",
            "cuir 2 cuir 10 ndealaich abair",
            "cuir 1 cuir 2 coimeas abair",
            "cuir 0.1 cuir 0.2 suim abair",
            "cuir 100000 tog suim abair cuir 3 tog bsuim abair",
        ] {
            assert_parity(src, "");
        }
    }

    #[test]
    fn compiled_parity_control_flow() {
        // countdown
        assert_parity("cuir 5 gcuairt chuir 0 mha cuìl criòch tog abair cuir 1 shuim criòch", "");
        // while with re-pushed conditions
        assert_parity("cuir 3 cuir 3 cuairt chuir 0 abair cuir 1 shuim tog criòch", "");
        // do-while with continue
        assert_parity(
            "cuir 3 chuairt chuir 0 abair cuir 1 shuim tog chuir 1 cuir 0 gcoimeas mha chuìl criòch criòch",
            "",
        );
        // if/else both arms
        assert_parity("cuir 1 ma cuir 10 abair no cuir 20 abair criòch", "");
        assert_parity("cuir 0 ma cuir 10 abair no cuir 20 abair criòch", "");
    }

    #[test]
    fn compiled_parity_examples() {
        let fib = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/fibonacci.gaidheal")).unwrap();
        assert_parity(&fib, "");
        let fb = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/fizzbuzz.gaidheal")).unwrap();
        assert_parity(&fb, "");
        let fail = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/failte.gaidheal")).unwrap();
        assert_parity(&fail, "");
        let fac = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/factarail.gaidheal")).unwrap();
        assert_parity(&fac, "");
        let cgd = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/cgd.gaidheal")).unwrap();
        assert_parity(&cgd, "48 18\n");
        let sum = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/examples/suim.gaidheal")).unwrap();
        assert_parity(&sum, "1 2 3 4 5\n");
    }

    #[test]
    fn compiled_parity_io_and_errors() {
        assert_parity("faigh faigh suim abair bhfaigh abair", "2 3");
        assert_parity("fhaigh abair fhaigh abair fhaigh abair", "aé");
        assert_parity("cuir 242 n-abair", "");
        assert_parity("cuir 5 dtog abair", "");
    }
}
